"""Generate the steel font and sprite tables (steel/gfx_data.c).

Run it when you want to change the look; the generated file is checked in,
so building the kernel needs neither Python nor the fonts.

Glyph sources (all freely licensed, see docs/CREDITS.md):
  DejaVu Sans / Sans Mono / Sans Bold   - text
  GNU FreeSerif                         - chess pieces
"""
import sys
from PIL import Image, ImageDraw, ImageFont

DEJAVU = "/usr/share/fonts/truetype/dejavu/"
FREE = "/usr/share/fonts/truetype/freefont/"

CELL_W, CELL_H = 12, 28
SPRITE = 64

# code page 437 control range as pictures
LOW = "\u0000☺☻♥♦♣♠•◘○◙♂♀♪♫☼►◄↕‼¶§▬↨↑↓→←∟↔▲▼"


def cp437_char(c):
    if c < 0x20:
        return LOW[c]
    if c == 0x7F:
        return "⌂"
    return bytes([c]).decode("cp437")


def alpha_of(ch, font, w, h, base):
    im = Image.new("L", (w, h), 0)
    ImageDraw.Draw(im).text((0, base), ch, font=font, fill=255, anchor="ls")
    return im


def emit_array(out, name, data, per_line=24):
    out.write("const unsigned char %s[%d] = {\n" % (name, len(data)))
    for i in range(0, len(data), per_line):
        out.write("\t" + ",".join("%d" % b for b in data[i:i + per_line]) + ",\n")
    out.write("};\n\n")


def main(path):
    out = open(path, "w")
    out.write("// SPDX-License-Identifier: GPL-2.0-only\n")
    out.write("/* GENERATED by scripts/genfont.py, do not edit.\n"
              " * Glyphs: DejaVu, GNU FreeSerif (docs/CREDITS.md). */\n")
    out.write('#include <steel/gfx.h>\n\n')

    # 1. the cell font: 12x28, all 256 code page 437 characters
    mono = ImageFont.truetype(DEJAVU + "DejaVuSansMono.ttf", 20)
    data = bytearray()
    for c in range(256):
        if 0xB0 <= c <= 0xDF:           # drawn as lines and blocks by steel
            data += bytes(CELL_W * CELL_H)
            continue
        ch = cp437_char(c)
        im = alpha_of(ch, mono, CELL_W, CELL_H, 22)
        if c == 0x20:
            im = Image.new("L", (CELL_W, CELL_H), 0)
        data += im.tobytes()
    emit_array(out, "gfx_font_cell_alpha", data)

    # 2/3. proportional UI fonts, ASCII 32..126
    for name, ttf, size, h, base, maxw in (
            ("ui", "DejaVuSans.ttf", 14, 18, 14, 14),
            ("uib", "DejaVuSans-Bold.ttf", 20, 26, 20, 20)):
        f = ImageFont.truetype(DEJAVU + ttf, size)
        alpha = bytearray()
        adv = bytearray()
        for c in range(32, 127):
            ch = chr(c)
            a = int(round(f.getlength(ch)))
            adv.append(min(max(a, 1), maxw))
            alpha += alpha_of(ch, f, maxw, h, base).tobytes()
        emit_array(out, "gfx_font_%s_alpha" % name, alpha)
        emit_array(out, "gfx_font_%s_adv" % name, adv)

    # 4. chess pieces: filled silhouettes, 64x64, order K Q R B N P
    ff = ImageFont.truetype(FREE + "FreeSerif.ttf", 62)
    sprites = bytearray()
    for ch in "♚♛♜♝♞♟":
        big = Image.new("L", (SPRITE * 2, SPRITE * 2), 0)
        ImageDraw.Draw(big).text((SPRITE, SPRITE * 2 - 28), ch, font=ff,
                                 fill=255, anchor="ms")
        bb = big.getbbox()
        big = big.crop(bb)
        # fit into 56x56 keeping aspect, centre on the sprite square
        scale = min(56 / big.width, 56 / big.height)
        sz = (max(1, round(big.width * scale)), max(1, round(big.height * scale)))
        big = big.resize(sz, Image.LANCZOS)
        sq = Image.new("L", (SPRITE, SPRITE), 0)
        sq.paste(big, ((SPRITE - sz[0]) // 2, SPRITE - 4 - sz[1]))
        sprites += sq.tobytes()
    emit_array(out, "gfx_chess_sprites", sprites)

    out.write("const struct gfx_font gfx_font_cell = {\n"
              "\t%d, %d, 0, 256, gfx_font_cell_alpha, 0, 22\n};\n\n" % (CELL_W, CELL_H))
    out.write("const struct gfx_font gfx_font_ui = {\n"
              "\t14, 18, 32, 95, gfx_font_ui_alpha, gfx_font_ui_adv, 14\n};\n\n")
    out.write("const struct gfx_font gfx_font_uib = {\n"
              "\t20, 26, 32, 95, gfx_font_uib_alpha, gfx_font_uib_adv, 20\n};\n")
    out.close()


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "steel/gfx_data.c")
