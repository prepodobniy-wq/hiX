"""Cross-check the Rust crypto module with Python-generated vectors.

The Python library is the reference implementation; the C program is linked
against the same Rust C ABI that the kernel uses. This is the intended place
to put a cipher from another team: generate vectors here, run them on the
host, then run the same code in hix (cryptotest / SYS_crypto).

Requires: pip install cryptography
Usage:   scripts/crypto_check.py [--seed N]
"""
import argparse
import random
import subprocess
import sys
from pathlib import Path

try:
    from cryptography.hazmat.primitives.ciphers import Cipher, algorithms
    from cryptography.hazmat.primitives.ciphers.aead import ChaCha20Poly1305
except ImportError:
    sys.exit("crypto_check: missing 'cryptography'; run: pip install cryptography")

ROOT = Path(__file__).resolve().parent.parent
BUILD = ROOT / "build" / "crypto"
RUST = BUILD / "libhix_rust_host.a"
C_FILE = BUILD / "vectors.c"
BINARY = BUILD / "vectors"


def rnd(rng, n):
    return bytes(rng.getrandbits(8) for _ in range(n))


def c_array(name, data):
    if not data:
        return f"static const unsigned char {name}[1] = {{ 0 }};\n"
    lines = [
        "static const unsigned char %s[%d] = {" % (name, len(data))
    ]
    for i in range(0, len(data), 12):
        lines.append("    " + ", ".join("0x%02x" % b for b in data[i:i + 12]) + ",")
    lines.append("};")
    return "\n".join(lines) + "\n"


def chacha20(key, nonce, counter, data):
    cipher = Cipher(
        algorithms.ChaCha20(key, counter.to_bytes(4, "little") + nonce),
        mode=None,
    )
    return cipher.encryptor().update(data)


def gen(seed):
    rng = random.Random(seed)
    stream = []
    for length in (0, 1, 15, 16, 64, 65, 257, 1000):
        key = rnd(rng, 32)
        nonce = rnd(rng, 12)
        counter = rng.randrange(0, 1 << 32)
        plain = rnd(rng, length)
        stream.append((key, nonce, counter, plain, chacha20(key, nonce, counter, plain)))

    aead = []
    for length, aad_len in ((0, 0), (1, 1), (16, 12), (17, 13), (64, 0),
                            (257, 33), (1000, 7)):
        key = rnd(rng, 32)
        nonce = rnd(rng, 12)
        aad = rnd(rng, aad_len)
        plain = rnd(rng, length)
        sealed = ChaCha20Poly1305(key).encrypt(nonce, plain, aad)
        aead.append((key, nonce, aad, plain, sealed[:-16], sealed[-16:]))
    return stream, aead


def emit(stream, aead):
    out = [
        "/* generated by scripts/crypto_check.py -- do not edit */",
        '#include <stdio.h>',
        '#include <string.h>',
        '#include "hix/cryptoabi.h"',
        "",
        "/* panic=abort still leaves this reference in the precompiled core */",
        "void rust_eh_personality(void)",
        "{",
        "}",
        "",
        'extern int hix_rust_selftest(void);',
        'extern unsigned int hix_rust_abi_version(void);',
        'extern int hix_rust_chacha20_xor(const unsigned char *, const unsigned char *,',
        '                                 unsigned int, unsigned char *, unsigned int);',
        'extern int hix_rust_aead_seal(const unsigned char *, const unsigned char *,',
        '                              const unsigned char *, unsigned int,',
        '                              const unsigned char *, unsigned int,',
        '                              unsigned char *, unsigned char *);',
        'extern int hix_rust_aead_open(const unsigned char *, const unsigned char *,',
        '                              const unsigned char *, unsigned int,',
        '                              const unsigned char *, unsigned int,',
        '                              unsigned char *, const unsigned char *);',
        "",
        "static int failures;",
        "",
        "static void check(int ok, const char *what)",
        "{",
        "\tif (!ok) {",
        '\t\tprintf("FAIL: %s\\n", what);',
        "\t\tfailures++;",
        "\t}",
        "}",
        "",
    ]

    for i, (key, nonce, counter, plain, expected) in enumerate(stream):
        n = len(plain)
        out.append(c_array(f"s{i}_key", key))
        out.append(c_array(f"s{i}_nonce", nonce))
        out.append(c_array(f"s{i}_plain", plain))
        out.append(c_array(f"s{i}_expected", expected))
        out.append(f"static void stream{i}(void)\n{{")
        out.append(f"\tunsigned char data[{max(n, 1)}];")
        out.append("\tint r;")
        out.append(f"\tmemcpy(data, s{i}_plain, {n});")
        out.append(f"\tr = hix_rust_chacha20_xor(s{i}_key, s{i}_nonce, {counter}u, data, {n}u);")
        out.append(f'\tcheck(r == 0 && memcmp(data, s{i}_expected, {n}) == 0, "chacha20 case {i} ({n} bytes)");')
        out.append("}\n")

    for i, (key, nonce, aad, plain, cipher, tag) in enumerate(aead):
        n = len(plain)
        out.append(c_array(f"a{i}_key", key))
        out.append(c_array(f"a{i}_nonce", nonce))
        out.append(c_array(f"a{i}_aad", aad))
        out.append(c_array(f"a{i}_plain", plain))
        out.append(c_array(f"a{i}_cipher", cipher))
        out.append(c_array(f"a{i}_tag", tag))
        out.append(f"static void aead{i}(void)\n{{")
        out.append(f"\tunsigned char out[{max(n, 1)}];")
        out.append(f"\tunsigned char back[{max(n, 1)}];")
        out.append("\tunsigned char tag[16];")
        out.append("\tint r;")
        out.append(f"\tr = hix_rust_aead_seal(a{i}_key, a{i}_nonce, a{i}_aad, {len(aad)}u, a{i}_plain, {n}u, out, tag);")
        out.append(f'\tcheck(r == 0 && memcmp(out, a{i}_cipher, {n}) == 0 && memcmp(tag, a{i}_tag, 16) == 0, "aead seal case {i} ({n} bytes)");')
        out.append(f"\tr = hix_rust_aead_open(a{i}_key, a{i}_nonce, a{i}_aad, {len(aad)}u, a{i}_cipher, {n}u, back, a{i}_tag);")
        out.append(f'\tcheck(r == 0 && memcmp(back, a{i}_plain, {n}) == 0, "aead open case {i} ({n} bytes)");')
        out.append("\ttag[0] ^= 0x80;")
        out.append(f"\tr = hix_rust_aead_open(a{i}_key, a{i}_nonce, a{i}_aad, {len(aad)}u, a{i}_cipher, {n}u, back, tag);")
        out.append(f'\tcheck(r == -74, "aead bad tag case {i}");')
        out.append("}\n")

    out.append("int main(void)\n{")
    out.append('\tprintf("crypto_check: Rust C ABI vs Python reference\\n");')
    out.append('\tcheck(hix_rust_abi_version() == HIX_CRYPTO_ABI, "ABI version");')
    out.append('\tcheck(hix_rust_selftest() == 0, "RFC 8439 selftest");')
    for i in range(len(stream)):
        out.append(f"\tstream{i}();")
    for i in range(len(aead)):
        out.append(f"\taead{i}();")
    out.append('\tif (failures) {')
    out.append('\t\tprintf("%d check(s) failed\\n", failures);')
    out.append("\t\treturn 1;")
    out.append("\t}")
    cases = len(stream) + len(aead) * 3 + 2
    out.append(f'\tprintf("crypto_check: all %d cases passed\\n", {cases});')
    out.append("\treturn 0;")
    out.append("}")
    return "\n".join(out) + "\n"


def run(cmd):
    print("+", " ".join(str(x) for x in cmd))
    subprocess.check_call(cmd)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--seed", type=int, default=0x484958)
    args = ap.parse_args()

    BUILD.mkdir(parents=True, exist_ok=True)
    stream, aead = gen(args.seed)
    C_FILE.write_text(emit(stream, aead))

    run([
        "rustc", "--edition", "2021", "--crate-name", "hix_rust",
        "--crate-type", "staticlib", "-C", "opt-level=2", "-C", "panic=abort",
        "-C", "debuginfo=0", "-o", str(RUST),
        str(ROOT / "rust" / "hix-core" / "src" / "lib.rs"),
    ])
    run([
        "cc", "-std=c11", "-O2", "-Wall", "-Wextra", "-Werror",
        "-I", str(ROOT / "include"), "-o", str(BINARY), str(C_FILE),
        str(RUST),
    ])
    run([str(BINARY)])


if __name__ == "__main__":
    main()
